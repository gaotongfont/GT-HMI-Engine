/**
 * @brief check unicode is symbol
 * 
 * @param unicode 
 * @return true is symbol
 * @return false no
 */
bool gt_symbol_check_by_unicode(uint32_t unicode)
{
    if( unicode > 0xF000 && unicode < 0xF8FF ){
        return true;
    }
    return false;
}

const uint8_t * gt_symbol_get_mask_buf(char * utf8)
{
    uint8_t cnt = sizeof(symbols)/sizeof(_gt_symbol_st);
    uint8_t idx = 0;
    while( idx < cnt ){
        if( memcmp(utf8, symbols[idx].utf8, 3) == 0 ){
            return symbols[idx].mask_buf;
        }
        idx++;
    }
    return NULL;
}

